    private readonly TContext db;
    private readonly IServiceProvider services;
    private readonly IForeignKeyWriteTracker fkWriteTracker;

    public PermissionAdminHandler(TContext db, IServiceProvider services, IForeignKeyWriteTracker fkWriteTracker)
    {
        this.db = db;
        this.services = services;
        this.fkWriteTracker = fkWriteTracker;
    }

    public bool HasPermission(ClaimsPrincipal user, params string[] permissions)
        => services.VerifyUserPermissions(permissions);

    public AdminContext GetContext(ClaimsPrincipal user)
    {
        var sysAdmin = IsSysAdmin();
        ApplyContextScope(sysAdmin);
        return new AdminContext
        {
            IsSysAdmin = sysAdmin,
            CurrentTenantId = db.CurrentTenantId
        };
    }

    public async Task<PagedResult<PermissionViewModel>> ListPermissionsAsync(ClaimsPrincipal user, int? tenantId, ListQuery query)
    {
        var sysAdmin = IsSysAdmin();
        ApplyContextScope(sysAdmin);

        IQueryable<TPermission> q;
        if (sysAdmin)
        {
            q = db.Permissions.AsNoTracking()
                .Where(p => p.TenantId == null || p.TenantId == tenantId);
        }
        else
        {
            db.HideGlobals = true;
            q = db.Permissions.AsNoTracking();
        }

        if (!string.IsNullOrWhiteSpace(query.Search))
        {
            var s = query.Search.Trim();
            q = q.Where(p => p.PermissionName.Contains(s) || (p.Description != null && p.Description.Contains(s)));
        }

        var total = await q.CountAsync();
        q = query.SortDescending ? q.OrderByDescending(p => p.PermissionName) : q.OrderBy(p => p.PermissionName);
        var items = await q.Skip(query.Page * query.PageSize).Take(query.PageSize)
            .Select(p => new PermissionViewModel
            {
                PermissionId = p.PermissionId,
                PermissionName = p.PermissionName,
                Description = p.Description,
                TenantId = p.TenantId ?? tenantId,
                IsGlobal = p.TenantId == null,
                Editable = sysAdmin || p.TenantId != null
            }).ToListAsync();
        return new PagedResult<PermissionViewModel> { Items = items, TotalCount = total };
    }

    public async Task<PermissionViewModel?> CreatePermissionAsync(ClaimsPrincipal user, int? tenantId, PermissionViewModel input)
    {
        if (!services.VerifyUserPermissions(new[] { "Permissions.Write" })) return null;
        var sysAdmin = IsSysAdmin();
        ApplyContextScope(sysAdmin);
        var effectiveTenantId = sysAdmin ? tenantId : db.CurrentTenantId;
        if (!sysAdmin && effectiveTenantId == null) return null;

        var entity = new TPermission
        {
            PermissionName = input.PermissionName,
            Description = input.Description,
            TenantId = effectiveTenantId
        };
        db.Permissions.Add(entity);
        await db.SaveChangesAsync();
        fkWriteTracker.MarkWritten("Permissions");
        input.PermissionId = entity.PermissionId;
        input.TenantId = effectiveTenantId;
        input.IsGlobal = effectiveTenantId == null;
        return input;
    }

    public async Task<PermissionViewModel?> UpdatePermissionAsync(ClaimsPrincipal user, PermissionViewModel input)
    {
        if (!services.VerifyUserPermissions(new[] { "Permissions.Write" })) return null;
        var sysAdmin = IsSysAdmin();
        ApplyContextScope(sysAdmin);
        var entity = await db.Permissions.FirstOrDefaultAsync(p => p.PermissionId == input.PermissionId);
        if (entity == null) return null;
        if (entity.TenantId == null && !sysAdmin) return null;

        entity.PermissionName = input.PermissionName;
        entity.Description = input.Description;
        await db.SaveChangesAsync();
        fkWriteTracker.MarkWritten("Permissions");
        return input;
    }

    public async Task<bool> DeletePermissionAsync(ClaimsPrincipal user, int permissionId)
    {
        if (!services.VerifyUserPermissions(new[] { "Permissions.Write" })) return false;
        var sysAdmin = IsSysAdmin();
        ApplyContextScope(sysAdmin);
        var entity = await db.Permissions.FirstOrDefaultAsync(p => p.PermissionId == permissionId);
        if (entity == null) return false;
        if (entity.TenantId == null && !sysAdmin) return false;

        db.Permissions.Remove(entity);
        await db.SaveChangesAsync();
        fkWriteTracker.MarkWritten("Permissions");
        return true;
    }

    private bool IsSysAdmin() => services.VerifyUserPermissions(new[] { ToolkitPermission.Sysadmin });

    private void ApplyContextScope(bool sysAdmin)
    {
        if (sysAdmin)
        {
            db.HideGlobals = false;
            db.ShowAllTenants = true;
        }
        else
        {
            db.HideGlobals = true;
            db.ShowAllTenants = false;
        }
    }
}
